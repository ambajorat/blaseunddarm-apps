fun tr(s: String): String = I18n.t(s)

/** Format-Variante: Platzhalter {0}, {1} ... werden nach der Uebersetzung ersetzt. */
fun trf(s: String, vararg args: Any?): String {
    var out = I18n.t(s)
    args.forEachIndexed { i, a -> out = out.replace("{$i}", a?.toString() ?: "") }
    return out
}
